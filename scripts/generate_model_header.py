"""Convert trained uint8 KDE surfaces to the ESP32 model.h header.
Student: Edryn Clyde Fernandez.
"""
from pathlib import Path
import json
import numpy as np


def c_float(value):
    """Emit a valid single-precision C++ literal, including zero."""
    out = f"{float(value):.9g}"
    if "." not in out and "e" not in out and "E" not in out:
        out += ".0"
    return out + "f"


def main():
    source = Path("outputs/surfaces.npz")
    if not source.exists():
        raise SystemExit("Run python scripts/train_model.py first.")
    with np.load(source) as d:
        tables = d["tables"]
        n = int(d["grid_n"])
        names = [str(k) for k in d["class_names"]]
        bounds = d["bounds"]
        tau = float(d["reject_tau"])
    if tables.ndim != 3 or tables.shape != (len(names), n, n) or tables.dtype != np.uint8:
        raise ValueError("Invalid quantized model table.")
    if bounds.shape != (4,) or not np.all(np.isfinite(bounds)):
        raise ValueError("Invalid model feature bounds.")
    lines = ["// Generated by scripts/generate_model_header.py",
             "// Student: Edryn Clyde Fernandez",
             "#pragma once", "#include <Arduino.h>", "#include <pgmspace.h>",
             f"#define GRID_N {n}", f"#define NUM_CLASSES {len(names)}",
             f"#define REJECT_TAU {c_float(tau)}",
             "const uint8_t CLASS_TABLE[NUM_CLASSES][GRID_N][GRID_N] PROGMEM = {"]
    for table in tables:
        lines.append("  {")
        for row in table:
            lines.append("    {" + ", ".join(str(int(x)) for x in row) + "},")
        lines.append("  },")
    lines += ["};",
              "const float SCALE_BOUNDS[4] = {" + ", ".join(c_float(v) for v in bounds) + "};",
              "const char* const CLASS_NAMES[NUM_CLASSES] = {" + ", ".join(json.dumps(s) for s in names) + "};",
              ""]
    dest = Path("firmware/inference/model.h")
    dest.parent.mkdir(parents=True, exist_ok=True)
    dest.write_text("\n".join(lines), encoding="utf-8")
    print(f"Generated {dest}: {tables.size} bytes table + 16 bytes bounds (excluding firmware/names).")


if __name__ == "__main__":
    main()
